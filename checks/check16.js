const { chromium } = require('playwright');
const fs = require('fs');
const libs = { 'js-yaml': 'node_modules/js-yaml/dist/js-yaml.min.js', 'marked': 'node_modules/marked/marked.min.js', 'dompurify': 'node_modules/dompurify/dist/purify.min.js' };
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.route('**/*', (route) => { const u = route.request().url(); for (const [k, f] of Object.entries(libs)) if (u.includes('cdnjs') && u.includes(k)) return route.fulfill({ body: fs.readFileSync(f), contentType: 'application/javascript' }); return u.startsWith('file:') ? route.continue() : route.abort(); });
  fs.writeFileSync('page.html', '<!doctype html><html><head><meta charset="utf-8"></head><body>' + fs.readFileSync('flows.html', 'utf8') + '</body></html>');
  await page.goto('file://' + process.cwd() + '/page.html');
  await page.waitForTimeout(300);
  const out = {};
  const nodes = async () => (await page.$$eval('#stage [data-node]', (n) => n.map((x) => x.getAttribute('data-node')))).filter((x) => !x.startsWith('storefront.'));
  out.before = await nodes();
  out.arrowsBefore = await page.locator('#stage [data-step]').count();
  await page.click('#stage .fold-btn[data-v="payments"]');
  await page.waitForTimeout(100);
  out.foldedPayments = await nodes();
  out.sub = await page.$$eval('#stage .centre-sub', (t) => t.map((x) => x.textContent));
  await page.click('[data-act="fold-all"][data-v="collapse"]');
  await page.waitForTimeout(100);
  out.allFolded = await nodes();
  out.arrowsAfter = await page.locator('#stage [data-step]').count();
  out.btnStates = await page.$$eval('[data-act="fold-all"]', (b) => b.map((x) => x.textContent + ':' + x.disabled));
  await page.screenshot({ path: 'shots/q7-fold.png' });
  await page.focus('#stage .fold-btn[data-v="fulfilment"]');
  await page.keyboard.press('Enter');
  await page.waitForTimeout(100);
  out.kbExpanded = (await nodes()).filter((x) => x.startsWith('fulfilment.'));
  out.focusKept = await page.evaluate(() => document.activeElement.getAttribute('data-v'));
  await page.click('[data-act="fold-all"][data-v="expand"]');
  out.expandedAgain = (await nodes()).length === out.before.length;
  // still able to add a step to a folded system's participant
  await page.click('[data-act="fold-all"][data-v="collapse"]');
  out.errors = errors;
  console.log(JSON.stringify(out, null, 1));
  await browser.close();
})();
