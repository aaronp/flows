const { chromium } = require('playwright');
const fs = require('fs');
const libs = { 'js-yaml': 'node_modules/js-yaml/dist/js-yaml.min.js', 'marked': 'node_modules/marked/marked.min.js', 'dompurify': 'node_modules/dompurify/dist/purify.min.js' };
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.route('**/*', (route) => { const u = route.request().url(); for (const [k, f] of Object.entries(libs)) if (u.includes('cdnjs') && u.includes(k)) return route.fulfill({ body: fs.readFileSync(f), contentType: 'application/javascript' }); return u.startsWith('file:') ? route.continue() : route.abort(); });
  fs.writeFileSync('page.html', '<!doctype html><html><head><meta charset="utf-8"></head><body>' + fs.readFileSync('flows.html', 'utf8') + '</body></html>');
  await page.goto('file://' + process.cwd() + '/page.html');
  await page.waitForTimeout(300);
  const out = {};
  await page.selectOption('#sys-pick', { label: 'Payments' });
  await page.waitForTimeout(150);
  await page.click('#file-menu-btn');
  out.items = await page.$$eval('#file-menu [role=menuitem]', (b) => b.map((x) => x.textContent));
  await page.click('#file-menu [data-act="sys-del"]');
  out.heading = await page.textContent('#sd-heading');
  out.body = (await page.textContent('#sd-body')).replace(/\s+/g, ' ');
  out.focus = await page.evaluate(() => document.activeElement.id);
  await page.locator('#modal .dialog').screenshot({ path: 'shots/q6-del.png' });
  await page.keyboard.press('Escape');
  out.closed = await page.locator('#modal').isHidden();
  out.focusBack = await page.evaluate(() => document.activeElement.id);
  await page.click('#file-menu-btn');
  await page.click('#file-menu [data-act="sys-del"]');
  await page.click('#modal [data-act="sys-del-yes"]');
  await page.waitForTimeout(150);
  out.systems = await page.$$eval('#sys-pick option', (o) => o.map((x) => x.textContent));
  out.toast = await page.textContent('#toast');
  await page.selectOption('#sys-pick', { label: 'Storefront' });
  await page.click('[data-act="md"]');
  await page.waitForTimeout(100);
  const md = await page.inputValue('#drawer textarea');
  out.stillRefsPayments = /payments/.test(md);
  out.errors = errors;
  console.log(JSON.stringify(out, null, 1));
  await browser.close();
})();
