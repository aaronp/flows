const { chromium } = require('playwright');
const fs = require('fs');
const libs = { 'js-yaml': 'node_modules/js-yaml/dist/js-yaml.min.js', 'marked': 'node_modules/marked/marked.min.js', 'dompurify': 'node_modules/dompurify/dist/purify.min.js' };
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.route('**/*', (route) => { const u = route.request().url(); for (const [k, f] of Object.entries(libs)) if (u.includes('cdnjs') && u.includes(k)) return route.fulfill({ body: fs.readFileSync(f), contentType: 'application/javascript' }); return u.startsWith('file:') ? route.continue() : route.abort(); });
  fs.writeFileSync('page.html', '<!doctype html><html><head><meta charset="utf-8"></head><body>' + fs.readFileSync('flows.html', 'utf8') + '</body></html>');
  await page.goto('file://' + process.cwd() + '/page.html');
  await page.waitForTimeout(300);
  const out = {};
  out.topButtons = await page.$$eval('#top .btn', (b) => b.map((x) => x.textContent.trim()).filter(Boolean));
  await page.click('#file-menu-btn');
  out.items = await page.$$eval('#file-menu [role=menuitem]', (b) => b.map((x) => x.textContent));
  out.focused = await page.evaluate(() => document.activeElement.textContent);
  await page.keyboard.press('ArrowDown'); await page.keyboard.press('ArrowDown');
  out.focused2 = await page.evaluate(() => document.activeElement.textContent);
  await page.screenshot({ path: 'shots/q4-menu.png', clip: { x: 0, y: 0, width: 1440, height: 260 } });
  await page.keyboard.press('Escape');
  out.closedEsc = await page.locator('#file-menu').count();
  out.focusBack = await page.evaluate(() => document.activeElement.id);
  await page.click('#file-menu-btn');
  await page.click('#stage', { position: { x: 20, y: 300 } });
  out.closedOutside = await page.locator('#file-menu').count();
  await page.click('#file-menu-btn');
  await page.click('#file-menu [data-act="new-sys"]');
  await page.waitForTimeout(100);
  out.afterNew = { menu: await page.locator('#file-menu').count(), focus: await page.evaluate(() => document.activeElement.id), sys: await page.$eval('#sys-pick', (s) => s.selectedOptions[0].textContent) };
  out.errors = errors;
  console.log(JSON.stringify(out, null, 1));
  await browser.close();
})();
