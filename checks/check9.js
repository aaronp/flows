const { chromium } = require('playwright');
const fs = require('fs');
const libs = { 'js-yaml': 'node_modules/js-yaml/dist/js-yaml.min.js', 'marked': 'node_modules/marked/marked.min.js', 'dompurify': 'node_modules/dompurify/dist/purify.min.js' };
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.route('**/*', (route) => { const u = route.request().url(); for (const [k, f] of Object.entries(libs)) if (u.includes('cdnjs') && u.includes(k)) return route.fulfill({ body: fs.readFileSync(f), contentType: 'application/javascript' }); return u.startsWith('file:') ? route.continue() : route.abort(); });
  fs.writeFileSync('page.html', '<!doctype html><html><head><meta charset="utf-8"></head><body>' + fs.readFileSync('flows.html', 'utf8') + '</body></html>');
  await page.goto('file://' + process.cwd() + '/page.html');
  await page.waitForTimeout(300);
  const out = {};
  await page.click('[data-act="flow-view"][data-v="sequence"]');
  out.lanes = await page.$$eval('.seq [data-node]', (g) => g.map((x) => x.getAttribute('data-node')));
  await page.click('.seq [data-step="3"] text');
  out.selected = await page.textContent('#right .nb');
  const at = async (sel) => { const b = await page.locator(sel).first().boundingBox(); await page.mouse.click(b.x + b.width / 2, b.y + b.height / 2); await page.waitForTimeout(80); };
  await page.keyboard.press('Escape');
  await at('.seq [data-node="storefront.inventory"] rect');
  out.pendingMark = await page.locator('.seq .seq-pending').count();
  await at('.seq [data-node="storefront.shopper"] rect');
  out.steps = await page.locator('#left [data-act="pick-step"]').count();
  out.newStep = await page.textContent('#right .nb');
  await page.screenshot({ path: 'shots/q1-seq.png' });
  await page.click('[data-act="flow-view"][data-v="orbit"]');
  out.orbitBack = await page.locator('#orbit').count();
  out.errors = errors;
  console.log(JSON.stringify(out));
  await browser.close();
})();
