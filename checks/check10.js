const { chromium } = require('playwright');
const fs = require('fs');
const libs = { 'js-yaml': 'node_modules/js-yaml/dist/js-yaml.min.js', 'marked': 'node_modules/marked/marked.min.js', 'dompurify': 'node_modules/dompurify/dist/purify.min.js' };
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.route('**/*', (route) => { const u = route.request().url(); for (const [k, f] of Object.entries(libs)) if (u.includes('cdnjs') && u.includes(k)) return route.fulfill({ body: fs.readFileSync(f), contentType: 'application/javascript' }); return u.startsWith('file:') ? route.continue() : route.abort(); });
  fs.writeFileSync('page.html', '<!doctype html><html><head><meta charset="utf-8"></head><body>' + fs.readFileSync('flows.html', 'utf8') + '</body></html>');
  await page.goto('file://' + process.cwd() + '/page.html');
  await page.waitForTimeout(300);
  const out = {};
  await page.click('[data-act="flow-view"][data-v="sequence"]');
  out.rowToggles = await page.$$eval('#left .asyncbtn', (b) => b.map((x) => x.textContent).join(','));
  out.acts = await page.$$eval('.seq .act', (b) => b.map((x) => x.getAttribute('data-act-for') + (x.classList.contains('async') ? '~' : '')).join(','));
  await page.locator('.seq').screenshot({ path: 'shots/q2-async.png' });
  await page.click('#left .asyncbtn[data-v="3"]');
  out.after = await page.$$eval('.seq .act', (b) => b.map((x) => x.getAttribute('data-act-for') + (x.classList.contains('async') ? '~' : '')).join(','));
  await page.click('#left [data-act="pick-step"][data-v="3"]');
  out.editorPressed = await page.$$eval('#right [data-act="step-async"]', (b) => b.map((x) => x.textContent + ':' + x.getAttribute('aria-pressed')).join(','));
  await page.click('#right [data-act="step-async"][data-v="sync"]');
  out.back = await page.textContent('#left .asyncbtn[data-v="3"]');
  await page.click('[data-act="md"]').catch(() => {});
  out.errors = errors;
  console.log(JSON.stringify(out));
  await browser.close();
})();
