const { chromium } = require('playwright');
const fs = require('fs');
const libs = { 'js-yaml': 'node_modules/js-yaml/dist/js-yaml.min.js', 'marked': 'node_modules/marked/marked.min.js', 'dompurify': 'node_modules/dompurify/dist/purify.min.js' };
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.route('**/*', (route) => { const u = route.request().url(); for (const [k, f] of Object.entries(libs)) if (u.includes('cdnjs') && u.includes(k)) return route.fulfill({ body: fs.readFileSync(f), contentType: 'application/javascript' }); return u.startsWith('file:') ? route.continue() : route.abort(); });
  fs.writeFileSync('page.html', '<!doctype html><html><head><meta charset="utf-8"></head><body>' + fs.readFileSync('flows.html', 'utf8') + '</body></html>');
  await page.goto('file://' + process.cwd() + '/page.html');
  await page.waitForTimeout(300);
  await page.click('[data-act="md"]');
  const lines = await page.evaluate(() => [document.getElementById('md-text').value.split('\n').length, document.getElementById('md-gutter').textContent.trim().split('\n').length]);
  const md = await page.inputValue('#md-text');
  await page.fill('#md-text', md.replace('chain: A', 'chain: 7'));
  await page.waitForTimeout(500);
  const bad = await page.textContent('#md-gutter .bad');
  const msg = await page.textContent('#md-msg');
  await page.evaluate(() => { const t = document.getElementById('md-text'); t.scrollTop = 600; t.dispatchEvent(new Event('scroll')); });
  const synced = await page.evaluate(() => Math.abs(document.getElementById('md-text').scrollTop - document.getElementById('md-gutter').scrollTop) < 2);
  await page.screenshot({ path: 'shots/m1-gutter.png' });
  console.log(JSON.stringify({ lines, bad, msg: msg.slice(0, 60), synced, errors }));
  await browser.close();
})();
