const { chromium } = require('playwright');
const fs = require('fs');
const libs = { 'js-yaml': 'node_modules/js-yaml/dist/js-yaml.min.js', 'marked': 'node_modules/marked/marked.min.js', 'dompurify': 'node_modules/dompurify/dist/purify.min.js' };
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.route('**/*', (route) => { const u = route.request().url(); for (const [k, f] of Object.entries(libs)) if (u.includes('cdnjs') && u.includes(k)) return route.fulfill({ body: fs.readFileSync(f), contentType: 'application/javascript' }); return u.startsWith('file:') ? route.continue() : route.abort(); });
  fs.writeFileSync('page.html', '<!doctype html><html><head><meta charset="utf-8"></head><body>' + fs.readFileSync('flows.html', 'utf8') + '</body></html>');
  await page.goto('file://' + process.cwd() + '/page.html');
  await page.waitForTimeout(300);
  const out = {};
  const names = () => page.$$eval('[id^="sf-name-"]', (i) => i.map((x) => x.value));
  const md = async () => { const v = await page.textContent('#sc-preview'); return v.replace(/\s+/g, ' '); };
  await page.click('#left [data-act="pick-step"][data-v="4"]');
  await page.click('.typepill .tp-x');
  await page.click('#tp-message');
  await page.keyboard.type('shipment notice');
  await page.keyboard.press('ArrowDown');
  await page.keyboard.press('Enter');
  await page.waitForTimeout(100);
  await page.keyboard.type('trackingId');
  await page.keyboard.press('Enter');
  out.afterEnter = await names();
  out.focus = await page.evaluate(() => document.activeElement.id);
  out.err1 = await page.$eval('#modal', (m) => (m.querySelector('.err') || {}).textContent || null);
  out.preview1 = await md();
  await page.keyboard.press('Enter');
  out.enterOnBlank = await names();
  await page.keyboard.type('carrier');
  await page.keyboard.press('Enter');
  await page.keyboard.type('eta');
  out.afterTyping = await names();
  // Enter in the middle inserts below
  await page.focus('#sf-name-0');
  await page.keyboard.press('Enter');
  out.inserted = await names();
  out.focus2 = await page.evaluate(() => document.activeElement.id);
  await page.click('#modal footer [data-act="sc-close"]');
  await page.click('[data-act="md"]');
  await page.waitForTimeout(100);
  out.saved = (await page.inputValue('#drawer textarea')).match(/shipment-notice:[\s\S]*?\n(?=\S)/)[0];
  out.errors = errors;
  console.log(JSON.stringify(out, null, 1));
  await browser.close();
})();
