const { chromium } = require('playwright');
const fs = require('fs');
const libs = { 'js-yaml': 'node_modules/js-yaml/dist/js-yaml.min.js', 'marked': 'node_modules/marked/marked.min.js', 'dompurify': 'node_modules/dompurify/dist/purify.min.js' };
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.route('**/*', (route) => { const u = route.request().url(); for (const [k, f] of Object.entries(libs)) if (u.includes('cdnjs') && u.includes(k)) return route.fulfill({ body: fs.readFileSync(f), contentType: 'application/javascript' }); return u.startsWith('file:') ? route.continue() : route.abort(); });
  fs.writeFileSync('page.html', '<!doctype html><html><head><meta charset="utf-8"></head><body>' + fs.readFileSync('flows.html', 'utf8') + '</body></html>');
  await page.goto('file://' + process.cwd() + '/page.html');
  await page.waitForTimeout(300);
  const out = {};
  await page.click('#left [data-act="pick-step"][data-v="2"]');
  out.check0 = (await page.textContent('#data-check')).replace(/\s+/g, ' ').trim();
  await page.click('.typepill .tp-link');
  out.options = await page.$$eval('#modal select optgroup[label="Built in"] option', (o) => [...new Set(o.map((x) => x.textContent))]);
  await page.click('[data-act="sf-add"]');
  const n = await page.$$eval('[id^="sf-name-"]', (i) => i.length);
  const sel = page.locator('#modal select').nth(n - 1);
  await sel.selectOption('date');
  await page.waitForTimeout(100);
  await page.click('#modal footer [data-act="sc-close"]');
  await page.waitForTimeout(100);
  out.data = await page.inputValue('#st-data');
  out.check = (await page.textContent('#data-check')).replace(/\s+/g, ' ').trim();
  await page.click('#data-check button');
  await page.waitForTimeout(100);
  out.filled = await page.inputValue('#st-data');
  out.errors = errors;
  console.log(JSON.stringify(out, null, 1));
  await browser.close();
})();
